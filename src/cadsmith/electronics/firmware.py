"""A PlatformIO project for the wired board: pins.h from the checked pin map, and a sketch.

The sketch is the project's own ``firmware/main.cpp`` when there is one; otherwise a starter that
brings every wired module up (servos to centre, the screen on, sensors printed to serial) so the
wiring can be tried before the real program is written. Flash with ``pio run -t upload``.
"""

from __future__ import annotations

import re

from cadsmith.electronics.wiring import Wiring, WiringReport

#: kind -> (platformio.ini [env] lines, Arduino core family)
BOARDS = {
    "esp32_devkit": (["platform = espressif32", "board = esp32dev"], "esp32"),
    "arduino_nano": (["platform = atmelavr", "board = nanoatmega328",
                      "; a Nano with the new bootloader: board = nanoatmega328new"], "avr"),
    "arduino_uno": (["platform = atmelavr", "board = uno"], "avr"),
    "pi_pico": (["platform = https://github.com/maxgerhardt/platform-raspberrypi.git", "board = pico",
                 "board_build.core = earlephilhower"], "pico"),
}
SERVO_KINDS = {"SG90", "MG90S", "MG996R"}
LIBS = {
    "servo": {"esp32": "madhephaestus/ESP32Servo", "avr": "arduino-libraries/Servo"},
    "pca9685": "adafruit/Adafruit PWM Servo Driver Library",
    "ssd1306": ["adafruit/Adafruit SSD1306", "adafruit/Adafruit GFX Library"],
    "mpu6050": "adafruit/Adafruit MPU6050",
}


def _ident(text: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", text.upper()).strip("_")


def _number(pin: str) -> str:
    """The Arduino name of a board pin: GPIO13 -> 13, D9 -> 9, A0 -> A0, GP5 -> 5."""
    for prefix in ("GPIO", "GP", "D"):
        if pin.startswith(prefix) and pin[len(prefix):].isdigit():
            return pin[len(prefix):]
    return pin


def firmware_files(wiring: Wiring, report: WiringReport, project: str, sketch: str | None = None) -> dict[str, str]:
    """``{path: text}`` of the PlatformIO project, or empty when no supported board is wired."""
    mcu = next((name for name, device in wiring.devices.items() if device.kind in BOARDS), None)
    if mcu is None:
        return {}
    env, core = BOARDS[wiring.devices[mcu].kind]
    defines, servos, pca_servos, modules = [], [], [], set()
    i2c: dict[str, str] = {}
    for entry in report.pins:
        board_pin = entry["pin"]
        if not board_pin.startswith(mcu + "."):
            continue
        number = _number(board_pin.partition(".")[2])
        for other in entry["to"]:
            device_name, _, pin = other.partition(".")
            device = wiring.devices[device_name]
            if entry["use"] in ("sda", "scl"):
                i2c[entry["use"]] = number
                modules.add(device.kind)
                continue
            if device.kind in SERVO_KINDS:
                macro = f"PIN_{_ident(device_name)}"
                servos.append((device_name, macro))
            else:
                macro = f"PIN_{_ident(device_name)}_{_ident(pin)}"
                modules.add(device.kind)
            defines.append((macro, number, f"{other} ({device.title})"))
    for net in report.nets:
        channel = next((ref for ref in net["pins"] if wiring.device(ref).kind == "pca9685"
                        and ref.partition(".")[2].startswith("PWM")), None)
        if channel:
            for ref in net["pins"]:
                if wiring.device(ref).kind in SERVO_KINDS:
                    name = ref.partition(".")[0]
                    pca_servos.append((name, f"CH_{_ident(name)}"))
                    defines.append((f"CH_{_ident(name)}", channel.partition(".")[2][3:], f"{channel} -> {ref}"))
    for use, number in sorted(i2c.items()):
        defines.append((f"PIN_I2C_{use.upper()}", number, "I2C bus"))

    pins_h = ["// Generated by cadsmith from the checked wiring. Do not edit: change WIRES in model.py.",
              f"// Board: {wiring.devices[mcu].title}", "#pragma once", ""]
    width = max((len(macro) for macro, _, _ in defines), default=0)
    pins_h += [f"#define {macro:<{width}} {number}  // {note}" for macro, number, note in defines]

    libs = []
    if servos and core in LIBS["servo"]:
        libs.append(LIBS["servo"][core])
    for kind in ("pca9685", "ssd1306", "mpu6050"):
        if kind in modules:
            libs += LIBS[kind] if isinstance(LIBS[kind], list) else [LIBS[kind]]
    ini = ["; Generated by cadsmith. Flash with: pio run -t upload", "", f"[env:{_ident(project).lower() or 'board'}]",
           *env, "framework = arduino", "monitor_speed = 115200"]
    if libs:
        ini += ["lib_deps ="] + [f"    {lib}" for lib in libs]

    main = sketch if sketch is not None else _starter(project, core, servos, pca_servos, modules, bool(i2c), defines)
    return {"src/main.cpp": main, "include/pins.h": "\n".join(pins_h) + "\n", "platformio.ini": "\n".join(ini) + "\n"}


def _starter(project, core, servos, pca_servos, modules, has_i2c, defines) -> str:
    sonar = [macro[: -len("_TRIG")] for macro, _, _ in defines if macro.endswith("_TRIG")]
    inc = ["#include <Arduino.h>", '#include "pins.h"']
    if has_i2c:
        inc.append("#include <Wire.h>")
    if servos:
        inc.append("#include <ESP32Servo.h>" if core == "esp32" else "#include <Servo.h>")
    if "pca9685" in modules:
        inc.append("#include <Adafruit_PWMServoDriver.h>")
    if "ssd1306" in modules:
        inc += ["#include <Adafruit_GFX.h>", "#include <Adafruit_SSD1306.h>"]
    if "mpu6050" in modules:
        inc.append("#include <Adafruit_MPU6050.h>")
    top = [f"// Starter for {project}: brings every wired module up so you can test the wiring.",
           "// Servos go to centre, the screen says hello, sensors print to the serial monitor (115200).",
           "// Replace it by asking for the real behaviour in the studio.", *inc, ""]
    for name, _ in servos:
        top.append(f"Servo {_ident(name).lower()};")
    if "pca9685" in modules:
        top.append("Adafruit_PWMServoDriver pca = Adafruit_PWMServoDriver(0x40);")
    if "ssd1306" in modules:
        top.append("Adafruit_SSD1306 screen(128, 64, &Wire, -1);")
    if "mpu6050" in modules:
        top.append("Adafruit_MPU6050 imu;")
    setup = ["void setup() {", "  Serial.begin(115200);"]
    if has_i2c:
        if core == "esp32":
            setup.append("  Wire.begin(PIN_I2C_SDA, PIN_I2C_SCL);")
        elif core == "pico":
            setup += ["  Wire.setSDA(PIN_I2C_SDA);", "  Wire.setSCL(PIN_I2C_SCL);", "  Wire.begin();"]
        else:
            setup.append("  Wire.begin();")
    for name, macro in servos:
        var = _ident(name).lower()
        setup += [f"  {var}.attach({macro});", f"  {var}.write(90);"]
    if "pca9685" in modules:
        setup += ["  pca.begin();", "  pca.setPWMFreq(50);"]
        for _, channel in pca_servos:
            setup.append(f"  pca.setPWM({channel}, 0, 307);  // about 1.5 ms: centre")
    if "ssd1306" in modules:
        setup += ["  if (screen.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {", "    screen.clearDisplay();",
                  "    screen.setTextColor(SSD1306_WHITE);", "    screen.setCursor(0, 0);",
                  f'    screen.println("{project[:20]}");', "    screen.display();",
                  '  } else Serial.println("screen not found: check SDA/SCL");']
    if "mpu6050" in modules:
        setup.append('  if (!imu.begin()) Serial.println("MPU6050 not found: check SDA/SCL");')
    for base in sonar:
        setup += [f"  pinMode({base}_TRIG, OUTPUT);", f"  pinMode({base}_ECHO, INPUT);"]
    setup += ['  Serial.println("ready");', "}"]
    loop = ["", "void loop() {"]
    for base in sonar:
        loop += [f"  digitalWrite({base}_TRIG, LOW); delayMicroseconds(2);",
                 f"  digitalWrite({base}_TRIG, HIGH); delayMicroseconds(10); digitalWrite({base}_TRIG, LOW);",
                 f"  Serial.printf(\"{base.removeprefix('PIN_').lower()} %.1f cm\\n\", pulseIn({base}_ECHO, HIGH, 30000) / 58.0);"
                 if core != "avr" else
                 f"  Serial.print(\"{base.removeprefix('PIN_').lower()} cm \"); "
                 f"Serial.println(pulseIn({base}_ECHO, HIGH, 30000) / 58.0);"]
    if "mpu6050" in modules:
        loop += ["  sensors_event_t a, g, t;", "  imu.getEvent(&a, &g, &t);",
                 '  Serial.print("accel z "); Serial.println(a.acceleration.z);']
    loop += ["  delay(500);", "}"]
    return "\n".join(top + [""] + setup + loop) + "\n"
